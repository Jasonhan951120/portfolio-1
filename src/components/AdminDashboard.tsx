// ── Animated SVG Donut Chart ─────────────────────────────────────────────
interface DonutSegment {
  label: string;
  count: number;
  color: string;
  hex: string;
}

function LeadDistributionPieChart({ segments, total, totalValue, currency }: { segments: DonutSegment[]; total: number; totalValue: number; currency: string }) {
  const [animated, setAnimated] = useState(false);

  useEffect(() => {
    const timer = setTimeout(() => setAnimated(true), 200);
    return () => clearTimeout(timer);
  }, []);

  const size = 180;
  const strokeWidth = 28;
  const radius = (size - strokeWidth) / 2;
  const circumference = 2 * Math.PI * radius;
  const cx = size / 2;
  const cy = size / 2;

  // Build dash segments
  let cumulativePercent = 0;
  const segmentElements = segments.map((seg, i) => {
    const percent = total > 0 ? seg.count / total : 0;
    const dashArray = circumference * percent;
    const dashOffset = circumference * (1 - cumulativePercent);
    cumulativePercent += percent;

    return (
      <circle
        key={seg.label}
        cx={cx}
        cy={cy}
        r={radius}
        fill="none"
        stroke={seg.hex}
        strokeWidth={strokeWidth}
        strokeDasharray={`${animated ? dashArray : 0} ${circumference}`}
        strokeDashoffset={dashOffset}
        strokeLinecap="butt"
        transform={`rotate(-90 ${cx} ${cy})`}
        style={{ transition: `stroke-dasharray 0.8s ease ${i * 0.15}s` }}
      />
    );
  });

  return (
    <div className="flex flex-col items-center">
      <div className="relative">
        <svg width={size} height={size}>
          {/* Background ring */}
          <circle
            cx={cx} cy={cy} r={radius}
            fill="none"
            stroke="#F1F5F9"
            strokeWidth={strokeWidth}
          />
          {segmentElements}
        </svg>
        {/* Centre label */}
        <div className="absolute inset-0 flex flex-col items-center justify-center gap-1 mt-1">
          <div className="flex flex-col items-center">
            <span className="text-xl font-bold text-slate-900 leading-none">{total}</span>
            <span className="text-[9px] text-slate-500 uppercase tracking-widest font-bold">Leads</span>
          </div>
          <div className="w-8 h-px bg-slate-100 my-0.5" />
          <div className="flex flex-col items-center">
            <span className="text-[15px] font-bold text-emerald-600 leading-none" data-hj-suppress>
              {currency}
              {(totalValue / 1000).toFixed(1)}k
            </span>
            <span className="text-[9px] text-slate-500 uppercase tracking-widest font-bold">Value</span>
          </div>
        </div>
      </div>

      {/* Legend */}
      <div className="mt-6 w-full space-y-3">
        {segments.map((seg) => {
          const pct = total > 0 ? Math.round((seg.count / total) * 100) : 0;
          return (
            <div key={seg.label} className="flex items-center justify-between">
              <div className="flex items-center gap-2">
                <div className="w-2.5 h-2.5 rounded-full flex-shrink-0" style={{ background: seg.hex }} />
                <span className="text-[11px] text-slate-500 font-medium">{seg.label}</span>
              </div>
              <span className="text-[11px] font-bold text-slate-900/80">
                {seg.count} <span className="text-slate-400">({pct}%)</span>
              </span>
            </div>
          );
        })}
      </div>
    </div>
  );
}

